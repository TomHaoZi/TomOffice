import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import mammoth from 'mammoth';
import JSZip from 'jszip';
const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'tom-office-test-'));
const out = path.resolve('test-results'); await fs.mkdir(out, { recursive: true });
const packaged = process.env.TOM_OFFICE_PACKAGED === '1';
const launch = () => electron.launch({ ...(packaged ? { executablePath: path.resolve('release/win-unpacked/Tom Office.exe') } : {}), args: packaged ? [] : ['.'], env: { ...process.env, TOM_OFFICE_TEST_PROFILE: profile } });
let app = await launch();
let page;
const errors = [];
try {
  page = await app.firstWindow();
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') console.error('RENDERER:', message.text()); });
  await page.getByRole('heading', { name: '你好，今天想创造些什么？' }).waitFor();
  await page.screenshot({ path: path.join(out, '01-home.png') });
  await page.getByRole('button', { name: /新建文字.*记录灵感/ }).click();
  const doc = page.locator('.document-paper'); await doc.waitFor(); await doc.click();
  await page.keyboard.type('Tom Office desktop test');
  assert.match(await doc.innerText(), /Tom Office desktop test/);
  await page.getByRole('button', { name: '插入', exact: true }).click();
  await page.getByRole('button', { name: '插入表格', exact: true }).click();
  await page.locator('.modal-actions').getByRole('button', { name: '插入表格' }).click();
  assert.equal(await doc.locator('td').count(), 9);
  await page.screenshot({ path: path.join(out, '02-document.png') });
  async function exportTo(extension) {
    const filePath = path.join(out, 'smoke.' + extension);
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, filePath);
    await page.locator('.export-button').click();
    await page.locator('.export-options').getByRole('button').filter({ hasText: extension === 'tom' ? 'Tom Office 文档' : extension.toUpperCase() + ' 通用办公格式' }).click();
    await page.locator('.modal-backdrop').waitFor({ state: 'hidden', timeout: 20000 }).catch(async error => { console.error('EXPORT FAILURE:', await page.locator('.toast').innerText().catch(() => 'no toast')); throw error; });
    await page.waitForFunction(() => !document.querySelector('.busy-overlay'));
    assert.ok((await fs.stat(filePath)).size > 50); return filePath;
  }
  const nativeFile = await exportTo('tom'); const docxFile = await exportTo('docx');
  assert.equal(JSON.parse(await fs.readFile(nativeFile, 'utf8')).type, 'doc');
  assert.match((await mammoth.extractRawText({ path: docxFile })).value, /Tom Office desktop test/);
  await page.locator('.home-tab').click();
  await page.getByRole('button', { name: /项目预算表/ }).click();
  await page.locator('[data-ref="D4"]').waitFor();
  assert.equal(await page.locator('[data-ref="D4"]>span').innerText(), '6500');
  await page.locator('[data-ref="B2"]').dblclick(); await page.locator('.cell-input').fill('16000'); await page.keyboard.press('Enter');
  assert.equal(await page.locator('[data-ref="D4"]>span').innerText(), '7500');
  await page.locator('.quick-toolbar').getByTitle('撤销', { exact: true }).click();
  assert.equal(await page.locator('[data-ref="D4"]>span').innerText(), '6500');
  await page.screenshot({ path: path.join(out, '03-spreadsheet.png') });
  const xlsx = await exportTo('xlsx');
  await app.evaluate(({ dialog }, filePath) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filePath] }); }, xlsx);
  await page.locator('.quick-toolbar').getByRole('button', { name: '打开', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.document-tab').length === 3 && !document.querySelector('.busy-overlay'));
  assert.equal(await page.locator('[data-ref="D4"]>span').innerText(), '6500');
  await page.locator('.home-tab').click(); await page.getByRole('button', { name: /极简项目提案/ }).click();
  await page.locator('.slide-canvas').waitFor();
  await page.getByRole('button', { name: '新建幻灯片', exact: true }).first().click();
  assert.equal(await page.locator('.slide-thumbnail').count(), 4);
  await page.getByRole('button', { name: '文本框', exact: true }).click();
  assert.equal(await page.locator('.slide-canvas .slide-element').count(), 2);
  await page.locator('.slide-canvas .slide-element.text').last().dblclick();
  await page.locator('.slide-canvas [contenteditable="true"]').fill('Edited presentation');
  await page.locator('.ribbon-tabs').getByRole('button', { name: '设计', exact: true }).click();
  await page.locator('.theme-swatch').filter({ hasText: '午夜蓝' }).click();
  await page.screenshot({ path: path.join(out, '04-presentation.png') });
  const pptxFile = await exportTo('pptx');
  const archive = await JSZip.loadAsync(await fs.readFile(pptxFile));
  assert.match(await archive.file('ppt/slides/slide2.xml').async('string'), /Edited presentation/);
  await page.getByRole('button', { name: '放映', exact: true }).first().click();
  await page.getByRole('button', { name: '开始放映', exact: true }).click();
  await page.locator('.slideshow').waitFor(); await page.keyboard.press('Escape'); await page.locator('.slideshow').waitFor({ state: 'hidden' });
  await page.waitForTimeout(1000);
  const workspace = JSON.parse(await fs.readFile(path.join(profile, 'workspace.json'), 'utf8'));
  assert.equal(workspace.files.length, 4); assert.equal(errors.length, 0, errors.join('\n'));
  await page.locator('.window-close').click();
  await new Promise(resolve => { if (app.process().exitCode !== null) resolve(); else app.process().once('exit', resolve); });
  app = await launch(); page = await app.firstWindow();
  await page.locator('.slide-canvas').waitFor();
  assert.equal(await page.locator('.document-tab').count(), 4);
  await page.locator('.document-tab').first().click();
  assert.match(await page.locator('.document-paper').innerText(), /Tom Office desktop test/);
  await app.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => { throw new Error('Unexpected dialog: grant was not restored'); }; });
  await page.locator('.quick-toolbar').getByTitle('保存 Ctrl+S').click();
  await page.getByText('文件已保存到本机', { exact: true }).waitFor();
  console.log('PASS: native window, document editing + table, spreadsheet formulas + undo, XLSX roundtrip, slides, native save/open, 4 validated exports, restart recovery and restored save grants.');
  console.log('Screenshots and exported fixtures:', out);
} finally {
  if (errors.length) console.error(errors);
  await app.close().catch(() => {});
  await fs.rm(profile, { recursive: true, force: true }).catch(() => {});
}
